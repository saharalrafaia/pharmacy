    private void tableAgentsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableAgentsMouseClicked
       
    
    int row = tableAgents.getSelectedRow();

    txtID.setText(tableAgents.getValueAt(row,0).toString());
    txtName.setText(tableAgents.getValueAt(row,1).toString());
    txtAge.setText(tableAgents.getValueAt(row,2).toString());
    txtPhone.setText(tableAgents.getValueAt(row,3).toString());

    String gender =
    tableAgents.getValueAt(row,4).toString();

    if(gender.equals("Male"))
        rdmale.setSelected(true);
    else
        rdfemale.setSelected(true);

    cmbCompany.setSelectedItem(
        tableAgents.getValueAt(row,5).toString()
    );

    }//GEN-LAST:event_tableAgentsMouseClicked

