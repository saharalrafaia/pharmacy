    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
     
    String gender="";

    if(rdmale.isSelected())
        gender="Male";

    if(rdfemale.isSelected())
        gender="Female";

    DefaultTableModel model =
    (DefaultTableModel)tableAgents.getModel();

    int row = tableAgents.getSelectedRow();

    if(row != -1)
    {
        model.setValueAt(txtID.getText(), row, 0);
        model.setValueAt(txtName.getText(), row, 1);
        model.setValueAt(txtAge.getText(), row, 2);
        model.setValueAt(txtPhone.getText(), row, 3);
        model.setValueAt(gender, row, 4);
        model.setValueAt(
            cmbCompany.getSelectedItem().toString(),
            row,
            5
        );
    }

    }//GEN-LAST:event_btnUpdateActionPerformed

